#!/usr/bin/env bash
# Regenerate the repo-root AGENTS.md + CLAUDE.md as a routing index over plugin AGENTS.md files.
#
# Why this script exists:
#   .gitignore lines 191-195 declare root AGENTS.md / CLAUDE.md as machine-generated artefacts
#   ("regenerated each session from plugin templates"). This is the regenerator. The output is
#   intentionally NOT committed — it is a per-checkout, per-session local artefact that primes
#   Claude Code's auto-load when a contributor starts a session at the repo root.
#
# What it produces:
#   AGENTS.md  — routing doc that points contributors at the right plugin AGENTS.md
#   CLAUDE.md  — single-line `@AGENTS.md` import so Claude Code's auto-load picks up the routing doc
#
# When to run it:
#   - Manually after adding/removing a plugin:  ./scripts/regenerate-agents.sh
#   - On SessionStart via your own .claude/settings.local.json (which IS gitignored, so the hook
#     is your personal preference — it does not impose on other contributors):
#       {"hooks": {"SessionStart": [{"hooks": [{"type": "command",
#         "command": "${CLAUDE_PROJECT_DIR}/scripts/regenerate-agents.sh"}]}]}}
#
# Inputs:
#   plugins/*/AGENTS.md           — discovered automatically
#   plugins/*/.claude-plugin/plugin.json — for the description field
#   .claude-plugin/marketplace.json — narrative ordering source
#
# Output is idempotent — re-running produces byte-identical content unless a plugin changes.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
cd "$REPO_ROOT"

OUT_AGENTS="$REPO_ROOT/AGENTS.md"
OUT_CLAUDE="$REPO_ROOT/CLAUDE.md"

# Collect plugin name + description pairs. Description comes from plugin.json; if absent or
# unparseable, fall back to "(no description)" rather than failing — keep the regenerator robust.
plugin_row() {
  local plugin_dir="$1"
  local name desc
  name="$(basename "$plugin_dir")"
  if [[ -f "$plugin_dir/.claude-plugin/plugin.json" ]]; then
    desc="$(python3 -c "import json,sys; print(json.load(open(sys.argv[1])).get('description','(no description)'))" "$plugin_dir/.claude-plugin/plugin.json" 2>/dev/null || echo "(no description)")"
  else
    desc="(no description)"
  fi
  printf '| `%s` | %s | [AGENTS.md](plugins/%s/AGENTS.md) |\n' "$name" "$desc" "$name"
}

# Render the routing doc. Order plugins by the marketplace.json ordering (the canonical
# narrative sequence: core -> contribute -> plan -> build -> orchestrate -> change -> ux -> ...).
# Plugins present on disk but not yet wired into marketplace.json are appended at the end so the
# regenerator still surfaces them — useful when a contributor adds a plugin directory before
# updating the marketplace entry.
ordered_plugins() {
  python3 <<'PY'
import json, pathlib
mp = json.load(open(pathlib.Path(".claude-plugin/marketplace.json")))
ordered = [p["source"].lstrip("./").rstrip("/") for p in mp.get("plugins", [])]
seen = set(ordered)
on_disk = sorted(str(p) for p in pathlib.Path("plugins").glob("*") if p.is_dir())
for src in ordered:
    print(src)
for src in on_disk:
    if src not in seen:
        print(src)
PY
}

cat > "$OUT_AGENTS" <<'HEADER'
<!-- AUTO-GENERATED by scripts/regenerate-agents.sh — DO NOT EDIT BY HAND. -->
<!-- Hand-edit the per-plugin plugins/<name>/AGENTS.md files; rerun the script to refresh. -->
<!-- markdownlint-disable MD013 -->
# makato — Contributor Routing

This repo is a **monorepo of Claude Code plugins**. Each plugin under `plugins/` owns its own
`AGENTS.md` with the rules, boundaries, and PR checklist that apply to that plugin only.

## Routing rule

**Before editing any file under `plugins/<name>/`, Read `plugins/<name>/AGENTS.md` first.** Its
"What Belongs Here", "Design Principles", "Security Model", and "PR Checklist" sections govern
that plugin's surface. Do not re-derive conventions from neighbouring plugins — each plugin's
contract is intentionally local.

When changes span multiple plugins, Read each affected plugin's `AGENTS.md` and reconcile only
where they explicitly integrate (e.g. `makato-orchestrate` dispatches `makato-build` skills —
that contract lives in both plugins' READMEs).

## Plugin index

| Plugin | Purpose | Guide |
|--------|---------|-------|
HEADER

while IFS= read -r plugin_path; do
  [[ -d "$plugin_path" ]] || continue
  [[ -f "$plugin_path/AGENTS.md" ]] || continue
  plugin_row "$plugin_path" >> "$OUT_AGENTS"
done < <(ordered_plugins)

cat >> "$OUT_AGENTS" <<'FOOTER'

The plugin marketplace itself is declared in [`.claude-plugin/marketplace.json`](.claude-plugin/marketplace.json).

## Cross-cutting changes

Some work touches files outside any single plugin: `.claude-plugin/marketplace.json`, `.github/`,
repo-level `README.md`, `CHANGELOG.md`, `scripts/`. For these, no per-plugin AGENTS.md applies —
the changes are governed by the repo's release-please + conventional-commits convention.
Title format: `type(scope): description` where `scope` is the plugin name when the change is
scoped, or omitted for repo-wide changes.

## Project specs convention

Plugins discover project specs via (in order):
1. `<REPO_ROOT>/makato.config.json` → `specsRoot` field
2. `<REPO_ROOT>/specs/index.yml`

No environment-variable fallback, no sibling-directory autodetect.
FOOTER

# CLAUDE.md is a one-line import so Claude Code's auto-load picks up AGENTS.md verbatim.
printf '@AGENTS.md\n' > "$OUT_CLAUDE"

echo "regenerated: $OUT_AGENTS  ($(wc -l < "$OUT_AGENTS") lines)"
echo "regenerated: $OUT_CLAUDE"
